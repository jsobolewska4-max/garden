// Plant database with spacing, companion planting, and schedule data

export interface PlantData {
  id: string;
  name: string;
  emoji: string;
  // Space needed per plant in inches
  spacingInches: number;
  // How many inches tall the plant grows (for layout: tall plants go north)
  heightCategory: "low" | "medium" | "tall" | "vine";
  // Sun requirement
  sun: "full" | "partial" | "shade";
  // Weeks before last frost to start seeds indoors (0 = direct sow only)
  startIndoorsWeeksBefore: number;
  // Weeks before/after last frost to transplant or direct sow outside
  // Negative = before last frost, positive = after last frost
  transplantWeeksFromFrost: number;
  // Can be direct sown?
  canDirectSow: boolean;
  // If direct sow, weeks relative to last frost
  directSowWeeksFromFrost: number;
  // Days to harvest from transplant/sow date
  daysToHarvest: number;
  // Good companion plants (by id)
  companions: string[];
  // Bad neighbors (by id)
  enemies: string[];
  // Can grow in containers?
  containerFriendly: boolean;
  // Minimum container depth in inches
  minContainerDepthInches: number;
  // Brief growing tip
  tip: string;
  // Fall planting support
  canFallPlant: boolean;
  // Weeks before first frost to direct sow for fall crop
  fallSowWeeksBeforeFirstFrost: number;
  // Weeks before first frost to start indoors for fall crop (0 = direct sow only)
  fallStartIndoorsWeeksBeforeFirstFrost: number;
  // How many seeds to sow per planting spot (for thinning)
  seedsPerSpot: number;
  // Whether seedlings need thinning
  needsThinning: boolean;
}

